namespace IndigoTailor.Cards.Common;

/// <summary>
/// C07 - 对合 (Margin Pull / Weft Shift)
/// 造成 6(9) 点伤害。将 1 张手牌置于最左端。
/// </summary>
public sealed class WeftShift() : IndigoTailorCard(
    baseCost: 1,
    type: CardType.Attack,
    rarity: CardRarity.Common,
    target: TargetType.AnyEnemy)
{
    public override bool IsScrapToken => false;
    public override IEnumerable<CardKeyword> CanonicalKeywords => [];

    protected override IEnumerable<DynamicVar> CanonicalVars =>
    [
        new DamageVar(6m, ValueProp.Move),
    ];

    protected override IEnumerable<IHoverTip> ExtraHoverTips =>
        GetDetectedKeywordTips("INDIGOTAILOR_SELVEDGE");

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay play)
    {
        ArgumentNullException.ThrowIfNull(play.Target);
        await DamageCmd.Attack(DynamicVars.Damage.BaseValue)
            .FromCard(this, play)
            .Targeting(play.Target)
            .WithHitFx("vfx/vfx_attack_slash")
            .Execute(choiceContext);

        if (Owner?.PlayerCombatState != null)
        {
            CardPile hand = Owner.PlayerCombatState.Hand;
            if (hand.Cards.Count > 1)
            {
                var prompt = RawScrapHelper.GetPrompt("INDIGOTAILOR-SELECT_TO_MOVE_SELVEDGE", CardSelectorPrefs.ExhaustSelectionPrompt);
                var chosen = await CommonActions.SelectSingleCard(this, prompt, choiceContext, PileType.Hand, c => c != this);
                if (chosen != null)
                {
                    hand.RemoveInternal(chosen, true);
                    hand.AddInternal(chosen, 0, true);
                    hand.InvokeContentsChanged();
                }
            }
        }

        await TriggerAttachedPatchesOnPlay(choiceContext, play.Target);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Damage.UpgradeValueBy(3m);
    }
}
